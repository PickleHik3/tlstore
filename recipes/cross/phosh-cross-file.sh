#!/bin/bash
# phosh-cross-file.sh — write the meson cross file for phoc, phosh and phosh-mobile-settings.
#
# Usage: TL_ARCH=aarch64|x86_64 ./phosh-cross-file.sh [output]     (default: ./cross-$TL_ARCH.ini)
#
# NDK clang for the Android triple, pkg-config pointed at the Termux sysroot that
# termux-sysroot.sh assembled (TL_SYSROOT, default ./sysroot, prefix TERMUX_PREFIX). meson turns
# the sys_root property into PKG_CONFIG_SYSROOT_DIR, so the .pc files keep their device paths
# and every -I/-L still lands inside the sysroot, as in build-fastfetch.sh.
# Env: TL_NDK (default $ANDROID_NDK_HOME, else ~/Android/Sdk/ndk/29.0.14206865), TL_ANDROID_API
# (default 26, build-asset.sh's MIN_API).
set -euo pipefail

TL_ARCH=${TL_ARCH:-aarch64}
NDK_VERSION=29.0.14206865
TL_NDK=${TL_NDK:-${ANDROID_NDK_HOME:-"${ANDROID_HOME:-$HOME/Android/Sdk}/ndk/$NDK_VERSION"}}
TL_ANDROID_API=${TL_ANDROID_API:-26}
TL_SYSROOT=${TL_SYSROOT:-"$PWD/sysroot"}
TERMUX_PREFIX=${TERMUX_PREFIX:-/data/data/com.termux/files/usr}
out=${1:-"$PWD/cross-$TL_ARCH.ini"}

case "$TL_ARCH" in
    aarch64 | x86_64) ;;
    *) echo "error: TL_ARCH must be aarch64 or x86_64, not $TL_ARCH" >&2; exit 2 ;;
esac
triple="$TL_ARCH-linux-android"
bin="$TL_NDK/toolchains/llvm/prebuilt/linux-x86_64/bin"
[ -x "$bin/$triple$TL_ANDROID_API-clang" ] || {
    echo "error: no NDK clang at $bin/$triple$TL_ANDROID_API-clang (set TL_NDK)" >&2
    exit 1
}
prefix="$TL_SYSROOT$TERMUX_PREFIX"
[ -d "$prefix/lib/pkgconfig" ] || {
    echo "error: no Termux sysroot at $prefix — run termux-sysroot.sh first" >&2
    exit 1
}

cat > "$out" <<EOF
# Generated by phosh-cross-file.sh for $TL_ARCH; do not edit.
[binaries]
c = '$bin/$triple$TL_ANDROID_API-clang'
cpp = '$bin/$triple$TL_ANDROID_API-clang++'
ar = '$bin/llvm-ar'
strip = '$bin/llvm-strip'
ranlib = '$bin/llvm-ranlib'
pkg-config = 'pkg-config'

[built-in options]
c_args = ['-I$prefix/include']
cpp_args = ['-I$prefix/include']
c_link_args = ['-L$prefix/lib', '-Wl,-rpath-link,$prefix/lib', '-Wl,-rpath,$TERMUX_PREFIX/lib']
cpp_link_args = ['-L$prefix/lib', '-Wl,-rpath-link,$prefix/lib', '-Wl,-rpath,$TERMUX_PREFIX/lib']

[properties]
sys_root = '$TL_SYSROOT'
pkg_config_libdir = ['$prefix/lib/pkgconfig', '$prefix/share/pkgconfig']
needs_exe_wrapper = true

[host_machine]
system = 'android'
cpu_family = '$TL_ARCH'
cpu = '$TL_ARCH'
endian = 'little'
EOF
echo "wrote $out"
